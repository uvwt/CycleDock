//go:build ignore

// 本脚本在 `sqlc generate` 后将 internal/store/db/db.go 改写为依赖 internal/sqldb，
// 使生成的全部查询方法天然运行在 PostgreSQL 与 SQLite 双数据库上，且零 pgx 直接依赖。
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const dbGoContent = `// Code generated by sqlc + scripts/patch_sqlc_db.go. DO NOT EDIT.

package db

import (
	"context"

	"github.com/uvwt/CycleDock/internal/sqldb"
)

type DBTX interface {
	Exec(context.Context, string, ...any) (sqldb.Result, error)
	Query(context.Context, string, ...any) (*sqldb.Rows, error)
	QueryRow(context.Context, string, ...any) *sqldb.Row
}

func New(db DBTX) *Queries {
	return &Queries{db: db}
}

type Queries struct {
	db DBTX
}

func (q *Queries) WithTx(tx *sqldb.Tx) *Queries {
	return &Queries{
		db: tx,
	}
}
`

func main() {
	outPath := filepath.Join("internal", "store", "db", "db.go")
	if err := os.WriteFile(outPath, []byte(dbGoContent), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write %s: %v\n", outPath, err)
		os.Exit(1)
	}

	// 检查生成的 *.sql.go 中是否还有 pgx 残留（通常不应有，但 DeleteRemovedWorkspaceModelRoutes 等特殊查询做显式检查）。
	entries, err := filepath.Glob(filepath.Join("internal", "store", "db", "*.go"))
	if err != nil {
		fmt.Fprintf(os.Stderr, "glob: %v\n", err)
		os.Exit(1)
	}
	for _, p := range entries {
		raw, err := os.ReadFile(p)
		if err != nil {
			fmt.Fprintf(os.Stderr, "read %s: %v\n", p, err)
			os.Exit(1)
		}
		if strings.Contains(string(raw), "github.com/jackc/pgx") {
			fmt.Fprintf(os.Stderr, "unexpected pgx import in %s\n", p)
			os.Exit(1)
		}
	}
}
